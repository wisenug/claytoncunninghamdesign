#!/usr/bin/env node
/* inject-colors.mjs: writes page colors from js/projects.js into the HTML.

   js/projects.js is the single source for each project's bgColor / fgColor.
   The pages are static and the CSP forbids inline scripts, so the colors are
   written into the markup at build time instead of applied at runtime:

   - each project page's :root --color-bg / --color-fg
   - <meta name="theme-color"> (any page that defines --color-bg)
   - each page's .next-project-bg, using the next project's bgColor
   - the home grid's per-card --card-bg / --card-fg block in index.html

   Idempotent: CI runs it and fails if the committed HTML differs.
   Usage: node inject-colors.mjs */

import fs from 'node:fs/promises';

const manifestSrc = await fs.readFile('js/projects.js', 'utf8');
const shim = {};
new Function('window', manifestSrc)(shim);
const projects = shim.CCD_PROJECTS;
const byHref = Object.fromEntries(projects.map(p => [p.href, p]));

const files = (await fs.readdir('.')).filter(f => f.endsWith('.html'));
const changed = [];

// Replace one custom property's value inside the page's first :root block.
function setRootVar(src, name, value, file) {
  const root = src.match(/:root\s*\{[^}]*\}/);
  if (!root) throw new Error(`${file}: no :root block`);
  const re = new RegExp(`(${name}:\\s*)[^;]+;`);
  if (!re.test(root[0])) throw new Error(`${file}: :root has no ${name}`);
  return src.replace(root[0], root[0].replace(re, `$1${value};`));
}

const CARD_START = '/* Card colors: generated by inject-colors.mjs from js/projects.js. Do not edit by hand. */';
const CARD_END = '/* End generated card colors */';

for (const file of files) {
  let src = await fs.readFile(file, 'utf8');
  if (src.includes('http-equiv="refresh"')) continue; // redirect stubs
  const before = src;
  const project = byHref[file];

  if (project) {
    src = setRootVar(src, '--color-bg', project.bgColor, file);
    src = setRootVar(src, '--color-fg', project.fgColor, file);
  }

  // Browser UI tint follows the page background.
  const bg = src.match(/:root\s*\{[^}]*--color-bg:\s*([^;]+);/)?.[1].trim();
  if (bg) {
    src = src.replace(/(<meta name="theme-color" content=")[^"]*(")/, `$1${bg}$2`);
  }

  // Next-project band takes the next project's background.
  const nextHref = src.match(/<a href="([^"]+)" class="next-project-title"/)?.[1];
  if (nextHref) {
    const next = byHref[nextHref];
    if (!next) throw new Error(`${file}: next project ${nextHref} is not in js/projects.js`);
    src = src.replace(
      /<div class="next-project-bg" aria-hidden="true"[^>]*><\/div>/,
      `<div class="next-project-bg" aria-hidden="true" style="background-color: ${next.bgColor};"></div>`
    );
  }

  // Home grid: one rule per card.
  if (file === 'index.html') {
    const rules = projects
      .filter(p => src.includes(`href="${p.href}" class="work-card"`))
      .map(p => `    .work-card[href="${p.href}"] { --card-bg: ${p.bgColor}; --card-fg: ${p.fgColor}; }`)
      .join('\n');
    const block = `    ${CARD_START}\n${rules}\n    ${CARD_END}`;
    const existing = new RegExp(`[ \\t]*${escapeRe(CARD_START)}[\\s\\S]*?${escapeRe(CARD_END)}`);
    if (existing.test(src)) src = src.replace(existing, block);
    else src = src.replace('  </style>', `\n${block}\n  </style>`);
  }

  if (src !== before) {
    await fs.writeFile(file, src);
    changed.push(file);
  }
}

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

console.log(changed.length ? `inject-colors: updated ${changed.join(', ')}` : 'inject-colors: up to date');
